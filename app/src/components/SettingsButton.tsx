/**
 * Global settings entry: a fixed top-right gear that carries the current
 * address in `?from=`, so the settings page can link back to this page.
 */
export function SettingsButton() {
  const location = useLocation();
  const from = encodeURIComponent(location.pathname + location.search);

  return (
    <Link
      to={`/settings?from=${from}`}
      className="settings-button"
      aria-label="Настройки"
      title="Настройки"
    >
      <GearIcon />
    </Link>
  );
}
